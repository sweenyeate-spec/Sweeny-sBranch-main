USE Oracle_Of_Shrimp;
CREATE TABLE IF NOT EXISTS Users (
    userID INTEGER PRIMARY KEY AUTO_INCREMENT,
    username VARCHAR(255) NOT NULL UNIQUE,
    passwrd VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    isAdmin BOOLEAN NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS Friend (
    friendID INTEGER PRIMARY KEY AUTO_INCREMENT,
    friendProfile VARCHAR(255)
);
CREATE TABLE IF NOT EXISTS FriendList (
    friendListID INTEGER PRIMARY KEY AUTO_INCREMENT,
    ownerUserID INTEGER NOT NULL,
    friendUserID INTEGER,
    FOREIGN KEY (ownerUserID) REFERENCES Users(userID),
    FOREIGN KEY (friendUserID) REFERENCES Friend(friendID)
);
CREATE TABLE IF NOT EXISTS Fortune (
    fortuneID INTEGER PRIMARY KEY AUTO_INCREMENT,
    fortuneDescription VARCHAR(255) NOT NULL
);
CREATE TABLE IF NOT EXISTS FortuneLog (
    FortuneLogID INTEGER PRIMARY KEY AUTO_INCREMENT,
    userID INTEGER NOT NULL,
    fortuneID INTEGER NOT NULL,
    fortuneCount INTEGER NOT NULL DEFAULT 0,
    FOREIGN KEY (userID) REFERENCES Users(userID),
    FOREIGN KEY (fortuneID) REFERENCES Fortune(fortuneID)
);
CREATE TABLE IF NOT EXISTS Shrimp (
    shrimpID INTEGER PRIMARY KEY AUTO_INCREMENT,
    ownerUserID INTEGER NOT NULL,
    shrimpName VARCHAR(255) NOT NULL,
    shrimpBirthday DATE NOT NULL,
    FOREIGN KEY (ownerUserID) REFERENCES Users(userID)
);
CREATE TABLE IF NOT EXISTS Cosmetic (
    cosmeticID INTEGER PRIMARY KEY AUTO_INCREMENT,
    rarityWeight INTEGER NOT NULL,
    cosmeticDescription VARCHAR(255),
    cosmeticType VARCHAR(255) NOT NULL,
    cosmeticFile MEDIUMBLOB,
    acquisitionDate DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS CosmeticList (
    cosmeticListID INTEGER PRIMARY KEY AUTO_INCREMENT,
    shrimpID INTEGER NOT NULL,
    cosmeticID INTEGER NOT NULL,
    equipped boolean NOT NULL DEFAULT 0,
    FOREIGN KEY (shrimpID) REFERENCES Shrimp(shrimpID),
    FOREIGN KEY (cosmeticID) REFERENCES Cosmetic(cosmeticID)
);